-- Función auxiliar para obtener el rol del usuario autenticado
CREATE OR REPLACE FUNCTION get_auth_user_role()
RETURNS VARCHAR AS $$
    SELECT r.nombre_rol 
    FROM usuarios u
    JOIN roles r ON u.id_rol = r.id_rol
    WHERE u.id_usuario = auth.uid()
    LIMIT 1;
$$ LANGUAGE sql SECURITY DEFINER;

-- Regla RLS: Administrador ve todos los tickets
CREATE POLICY "admin_all_tickets" ON tickets
    FOR ALL
    USING (get_auth_user_role() = 'administrador');

-- Regla RLS: Técnico ve solo tickets con asignación vigente
CREATE POLICY "tech_assigned_tickets" ON tickets
    FOR SELECT
    USING (
        get_auth_user_role() = 'tecnico' AND
        id_ticket IN (SELECT id_ticket FROM asignaciones WHERE id_tecnico = auth.uid() AND activa = TRUE)
    );

-- Regla RLS: Usuario ve solo sus propios tickets
CREATE POLICY "user_own_tickets" ON tickets
    FOR SELECT
    USING (
        get_auth_user_role() = 'usuario' AND
        id_usuario_creador = auth.uid()
    );

-- Regla RLS: Notificaciones solo visibles para su destinatario
CREATE POLICY "user_own_notifications" ON notificaciones
    FOR ALL
    USING (id_usuario = auth.uid());

