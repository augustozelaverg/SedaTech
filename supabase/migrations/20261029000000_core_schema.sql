-- Función 1: Crear ticket con código secuencial atómico
CREATE OR REPLACE FUNCTION sp_crear_ticket(
    p_asunto VARCHAR(140),
    p_descripcion TEXT,
    p_categoria_id BIGINT,
    p_equipo_modelo VARCHAR(120) DEFAULT NULL,
    p_prioridad_id SMALLINT DEFAULT 2
)
RETURNS BIGINT AS $$
DECLARE
    v_ticket_id BIGINT;
    v_codigo VARCHAR(25);
    v_seq_num BIGINT;
    v_user_id UUID := auth.uid();
BEGIN
    SELECT COALESCE(MAX(id_ticket), 0) + 1 INTO v_seq_num FROM tickets;
    v_codigo := 'TK-' || TO_CHAR(CURRENT_DATE, 'YYYY') || '-' || LPAD(v_seq_num::TEXT, 5, '0');

    INSERT INTO tickets (
        codigo_ticket, asunto, descripcion, equipo_modelo, 
        id_usuario_creador, id_categoria, id_prioridad, id_estado
    ) VALUES (
        v_codigo, p_asunto, p_descripcion, p_equipo_modelo,
        v_user_id, p_categoria_id, p_prioridad_id, 1 -- 1 = Pendiente
    ) RETURNING id_ticket INTO v_ticket_id;

    -- Registro en Historial
    INSERT INTO historial_ticket (id_ticket, id_usuario_accion, accion, detalle)
    VALUES (v_ticket_id, v_user_id, 'ticket_creado', 'Ticket creado con código ' || v_codigo);

    RETURN v_ticket_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Función 2: Asignar Técnico (RF-04)
CREATE OR REPLACE FUNCTION sp_asignar_tecnico(
    p_ticket_id BIGINT,
    p_tecnico_id UUID
)
RETURNS VOID AS $$
DECLARE
    v_user_id UUID := auth.uid();
    v_admin_role VARCHAR := get_auth_user_role();
    v_estado_actual SMALLINT;
    v_codigo VARCHAR;
BEGIN
    IF v_admin_role != 'administrador' THEN
        RAISE EXCEPTION 'Solo un administrador puede asignar técnicos.';
    END IF;

    SELECT id_estado, codigo_ticket INTO v_estado_actual, v_codigo FROM tickets WHERE id_ticket = p_ticket_id FOR UPDATE;

    IF v_estado_actual != 1 THEN -- Pendiente
        RAISE EXCEPTION 'Solo se pueden asignar tickets en estado Pendiente.';
    END IF;

    -- Cerrar asignación anterior si existiese
    UPDATE asignaciones SET activa = FALSE, fecha_fin_asignacion = NOW() WHERE id_ticket = p_ticket_id AND activa = TRUE;

    -- Crear nueva asignación
    INSERT INTO asignaciones (id_ticket, id_tecnico) VALUES (p_ticket_id, p_tecnico_id);

    -- Historial
    INSERT INTO historial_ticket (id_ticket, id_usuario_accion, accion, detalle)
    VALUES (p_ticket_id, v_user_id, 'tecnico_asignado', 'Asignado técnico ID ' || p_tecnico_id);

    -- Notificación al técnico
    INSERT INTO notificaciones (id_usuario, id_ticket, titulo, mensaje, tipo)
    VALUES (p_tecnico_id, p_ticket_id, 'Nuevo Ticket Asignado', 'Se te ha asignado el ticket ' || v_codigo, 'info');
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Función 3: Iniciar Atención (RF-05, RF-06)
CREATE OR REPLACE FUNCTION sp_iniciar_atencion(p_ticket_id BIGINT)
RETURNS VOID AS $$
DECLARE
    v_user_id UUID := auth.uid();
    v_creador_id UUID;
    v_codigo VARCHAR;
BEGIN
    SELECT id_usuario_creador, codigo_ticket INTO v_creador_id, v_codigo 
    FROM tickets WHERE id_ticket = p_ticket_id FOR UPDATE;

    UPDATE tickets 
    SET id_estado = 2, -- En atención
        fecha_inicio_atencion = NOW(),
        updated_at = NOW()
    WHERE id_ticket = p_ticket_id;

    -- Historial
    INSERT INTO historial_ticket (id_ticket, id_usuario_accion, accion, detalle)
    VALUES (p_ticket_id, v_user_id, 'atencion_iniciada', 'El técnico inició la atención del equipo');

    -- Notificación al creador (RF-06)
    INSERT INTO notificaciones (id_usuario, id_ticket, titulo, mensaje, tipo)
    VALUES (v_creador_id, p_ticket_id, 'Atención Iniciada', 'El técnico ha iniciado el diagnóstico y reparación de tu ticket ' || v_codigo, 'info');
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Función 4: Resolver Ticket (RF-05)
CREATE OR REPLACE FUNCTION sp_resolver_ticket(
    p_ticket_id BIGINT,
    p_solucion TEXT,
    p_tiempo_min INTEGER DEFAULT 30
)
RETURNS VOID AS $$
DECLARE
    v_user_id UUID := auth.uid();
    v_creador_id UUID;
    v_codigo VARCHAR;
BEGIN
    IF TRIM(COALESCE(p_solucion, '')) = '' THEN
        RAISE EXCEPTION 'La solución técnica es obligatoria para resolver el ticket.';
    END IF;

    SELECT id_usuario_creador, codigo_ticket INTO v_creador_id, v_codigo 
    FROM tickets WHERE id_ticket = p_ticket_id FOR UPDATE;

    INSERT INTO soluciones (id_ticket, descripcion_solucion, tiempo_resolucion_min, id_tecnico_resuelve)
    VALUES (p_ticket_id, p_solucion, p_tiempo_min, v_user_id);

    UPDATE tickets 
    SET id_estado = 3, -- Resuelto
        fecha_resolucion = NOW(),
        updated_at = NOW()
    WHERE id_ticket = p_ticket_id;

    -- Historial
    INSERT INTO historial_ticket (id_ticket, id_usuario_accion, accion, detalle)
    VALUES (p_ticket_id, v_user_id, 'ticket_resuelto', 'Ticket resuelto con solución: ' || SUBSTRING(p_solucion FROM 1 FOR 60) || '...');

    -- Notificación al creador
    INSERT INTO notificaciones (id_usuario, id_ticket, titulo, mensaje, tipo)
    VALUES (v_creador_id, p_ticket_id, 'Ticket Resuelto', 'Tu ticket ' || v_codigo || ' ha sido resuelto con éxito.', 'success');
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;
