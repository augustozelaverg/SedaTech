-- 1. Habilitar extensión UUID
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. TABLA: roles
CREATE TABLE IF NOT EXISTS roles (
    id_rol SMALLINT PRIMARY KEY,
    nombre_rol VARCHAR(30) UNIQUE NOT NULL,
    descripcion VARCHAR(150)
);

-- 3. TABLA: usuarios (Perfiles autorizados vinculados a Auth)
CREATE TABLE IF NOT EXISTS usuarios (
    id_usuario UUID PRIMARY KEY,
    nombres VARCHAR(80) NOT NULL,
    apellidos VARCHAR(80) NOT NULL,
    correo VARCHAR(150) UNIQUE NOT NULL,
    id_rol SMALLINT NOT NULL REFERENCES roles(id_rol),
    cargo VARCHAR(80),
    avatar_color VARCHAR(20) DEFAULT '#377BF5',
    avatar_emoji VARCHAR(10) DEFAULT '👤',
    estado_usuario BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. TABLA: categorias
CREATE TABLE IF NOT EXISTS categorias (
    id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_categoria VARCHAR(60) UNIQUE NOT NULL,
    descripcion VARCHAR(150),
    icono VARCHAR(30) DEFAULT 'tag'
);

-- 5. TABLA: prioridades
CREATE TABLE IF NOT EXISTS prioridades (
    id_prioridad SMALLINT PRIMARY KEY,
    nombre_prioridad VARCHAR(12) UNIQUE NOT NULL,
    nivel_orden SMALLINT UNIQUE NOT NULL,
    descripcion VARCHAR(150),
    color_hex VARCHAR(10) NOT NULL
);

-- 6. TABLA: estados_ticket
CREATE TABLE IF NOT EXISTS estados_ticket (
    id_estado SMALLINT PRIMARY KEY,
    nombre_estado VARCHAR(20) UNIQUE NOT NULL,
    descripcion VARCHAR(150),
    color_hex VARCHAR(10) NOT NULL
);

-- 7. TABLA: tickets (Incidencias y Reparaciones)
CREATE TABLE IF NOT EXISTS tickets (
    id_ticket BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_ticket VARCHAR(25) UNIQUE NOT NULL,
    asunto VARCHAR(140) NOT NULL,
    descripcion TEXT NOT NULL,
    equipo_modelo VARCHAR(120),
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    id_usuario_creador UUID NOT NULL REFERENCES usuarios(id_usuario),
    id_categoria BIGINT NOT NULL REFERENCES categorias(id_categoria),
    id_prioridad SMALLINT NULL REFERENCES prioridades(id_prioridad),
    id_estado SMALLINT NOT NULL DEFAULT 1 REFERENCES estados_ticket(id_estado),
    fecha_inicio_atencion TIMESTAMPTZ NULL,
    fecha_resolucion TIMESTAMPTZ NULL,
    fecha_cancelacion TIMESTAMPTZ NULL,
    motivo_cancelacion TEXT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 8. TABLA: asignaciones (Historial de Asignaciones de Técnicos)
CREATE TABLE IF NOT EXISTS asignaciones (
    id_asignacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ticket BIGINT NOT NULL REFERENCES tickets(id_ticket) ON DELETE CASCADE,
    id_tecnico UUID NOT NULL REFERENCES usuarios(id_usuario),
    fecha_asignacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_fin_asignacion TIMESTAMPTZ NULL,
    observacion TEXT NULL,
    activa BOOLEAN NOT NULL DEFAULT TRUE
);

-- 9. TABLA: soluciones (Resolución Técnica Obligatoria)
CREATE TABLE IF NOT EXISTS soluciones (
    id_solucion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ticket BIGINT NOT NULL UNIQUE REFERENCES tickets(id_ticket) ON DELETE CASCADE,
    descripcion_solucion TEXT NOT NULL,
    tiempo_resolucion_min INTEGER NOT NULL DEFAULT 30,
    fecha_solucion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    id_tecnico_resuelve UUID NOT NULL REFERENCES usuarios(id_usuario)
);

-- 10. TABLA: historial_ticket (Auditoría Inalterable)
CREATE TABLE IF NOT EXISTS historial_ticket (
    id_historial BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ticket BIGINT NOT NULL REFERENCES tickets(id_ticket) ON DELETE CASCADE,
    id_usuario_accion UUID NOT NULL REFERENCES usuarios(id_usuario),
    accion VARCHAR(50) NOT NULL,
    detalle TEXT NULL,
    old_value TEXT NULL,
    new_value TEXT NULL,
    cambios JSONB NULL,
    fecha_hora TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 11. TABLA: notificaciones
CREATE TABLE IF NOT EXISTS notificaciones (
    id_notificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario UUID NOT NULL REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
    id_ticket BIGINT NOT NULL REFERENCES tickets(id_ticket) ON DELETE CASCADE,
    titulo VARCHAR(100) NOT NULL,
    mensaje TEXT NOT NULL,
    tipo VARCHAR(20) NOT NULL DEFAULT 'info',
    leido BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_envio TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 12. TABLA: reportes_exportados
CREATE TABLE IF NOT EXISTS reportes_exportados (
    id_reporte BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario UUID NOT NULL REFERENCES usuarios(id_usuario),
    filtro_fecha_inicio DATE NULL,
    filtro_fecha_fin DATE NULL,
    filtro_estado VARCHAR(20) NULL,
    filtro_prioridad VARCHAR(12) NULL,
    formato_exportacion VARCHAR(10) NOT NULL DEFAULT 'CSV',
    fecha_generacion TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ==============================================================================
-- ÍNDICES DE RENDIMIENTO Y CONCURRENCIA
-- ==============================================================================
CREATE UNIQUE INDEX IF NOT EXISTS idx_tickets_codigo ON tickets(codigo_ticket);
CREATE INDEX IF NOT EXISTS idx_tickets_estado_prioridad_fecha ON tickets(id_estado, id_prioridad, fecha_creacion ASC);
CREATE INDEX IF NOT EXISTS idx_tickets_creador_fecha ON tickets(id_usuario_creador, fecha_creacion DESC);
CREATE INDEX IF NOT EXISTS idx_asignaciones_activa_tecnico ON asignaciones(id_tecnico, activa) WHERE activa = TRUE;
CREATE UNIQUE INDEX IF NOT EXISTS idx_asignacion_activa_unica_por_ticket ON asignaciones(id_ticket) WHERE activa = TRUE;
CREATE INDEX IF NOT EXISTS idx_historial_ticket_fecha ON historial_ticket(id_ticket, fecha_hora ASC);
CREATE INDEX IF NOT EXISTS idx_notificaciones_usuario_leido ON notificaciones(id_usuario, leido, fecha_envio DESC);

